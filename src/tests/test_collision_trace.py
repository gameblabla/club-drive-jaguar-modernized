#!/usr/bin/env python3
"""GPU_TRACE runtime trace regression checks with deliberate negative fixtures."""
from __future__ import annotations
import sys
import unittest
import csv
import tempfile
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent.parent/'build'))
import verify_collision_trace as v

class TestV30Trace(unittest.TestCase):
 @classmethod
 def setUpClass(cls):cls.data=v.analyze()
 def test_real_bios_1800_fields(self):self.assertEqual(self.data['fields'],1800)
 def test_all_probes(self):self.assertEqual(self.data['probe_targets'],34)
 def test_unique_row_grid(self):self.assertEqual(self.data['csv_rows'],1800*34)
 def test_case_collision_loop(self):self.assertEqual(next(p['instruction_entries'] for p in self.data['probes'] if p['overlay']=='casend' and p['probe']=='closeLp'),68226)
 def test_first_collision_field(self):self.assertEqual(next(p['first_field'] for p in self.data['probes'] if p['overlay']=='casend' and p['probe']=='crashlp'),1037)
 def test_first_edge_test(self):self.assertEqual(next(p['first_field'] for p in self.data['probes'] if p['overlay']=='casend' and p['probe']=='crashedge'),1063)
 def test_genuine_hit(self):self.assertEqual(next(p['instruction_entries'] for p in self.data['probes'] if p['overlay']=='casend' and p['probe']=='edgehit'),20)
 def test_force_store_path(self):self.assertEqual(next(p['instruction_entries'] for p in self.data['probes'] if p['overlay']=='casend' and p['probe']=='force_store'),382)
 def test_nonzero_force_samples(self):self.assertEqual([x['field'] for x in self.data['nonzero_force_vectors']],[1065,1067])
 def test_signed_fixed_point_sample(self):self.assertEqual(self.data['nonzero_force_vectors'][0]['raw_xyz'],[0,-30815,0])
 def test_absent_other_game_modes(self):self.assertEqual(sum(p['instruction_entries'] for p in self.data['probes'] if p['overlay'] in ('tagend','racend')),0)
 def test_emulator_screenshot_parity(self):self.assertEqual(len(v.screenshot_check()),3)
 def test_original_rom_size(self):
  if not v.ROM.is_file():self.skipTest('ROM is generated by the source build')
  self.assertEqual(v.ROM.stat().st_size,2097152)
 def test_original_rom_digest(self):
  if not v.ROM.is_file():self.skipTest('ROM is generated by the source build')
  self.assertEqual(v.digest(v.ROM),'dd8062993e50cd0bc4b0ca67b04312360fe5b9d2287c8fd53283a011add07289')
 def test_reproducible_summary(self):self.assertEqual(dict(self.data,uninstrumented_screenshot_parity=v.screenshot_check()),__import__('json').loads(v.REPORT.read_text()))
 def test_real_source_image_signature(self):self.assertIn('GPUGetRAM', (v.BASE/'emulator/virtualjaguar_contact.patch').read_text())
 def test_patch_maintains_original_rom(self):self.assertNotIn('CLUB_reconstructed', (v.BASE/'emulator/virtualjaguar_contact.patch').read_text())
 def test_malformed_header_rejected(self):
  with tempfile.TemporaryDirectory() as td:
   p=Path(td)/'bad.csv';p.write_text('field,garbage\n')
   with self.assertRaises(ValueError):v.analyze(p)
 def test_malformed_row_rejected(self):
  with tempfile.TemporaryDirectory() as td:
   p=Path(td)/'bad.csv'
   with v.TRACE.open() as f:
    lines=f.readlines()
   lines[1]=lines[1].replace(',0xF03160,',',0x000000,')
   p.write_text(''.join(lines))
   with self.assertRaises(ValueError):v.analyze(p)
 def test_duplicate_row_rejected(self):
  with tempfile.TemporaryDirectory() as td:
   p=Path(td)/'bad.csv';s=v.TRACE.read_text();p.write_text(s+s.splitlines(True)[1])
   with self.assertRaises(ValueError):v.analyze(p)

if __name__=='__main__':unittest.main(verbosity=2)
