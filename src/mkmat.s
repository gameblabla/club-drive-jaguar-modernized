; mkmat.s - computes a rotation matrix
;	a 3x3 matrix is placed at address in a1
;
;	/* init matrix */
;	xrite =	matrix[0] = cos(gamma) * cos(beta) + sin(gamma) * sin(beta) * sin(alpha);
;	yrite = matrix[1] = sin(gamma) * cos(alpha);
;	zrite = matrix[2] = sin(gamma) * sin(alpha) * cos(beta) - cos(gamma) * sin(beta);
;	xdown = matrix[3] = cos(gamma) * sin(alpha) * sin(beta) - sin(gamma) * cos(beta);
;	ydown = matrix[4] = cos(gamma) * cos(alpha);
;	zdown = matrix[5] = cos(gamma) * sin(alpha) * cos(beta) + sin(gamma) * sin(beta);
;	xhead = matrix[6] = sin(beta) * cos(alpha);
;	yhead = matrix[7] = -sin(alpha);
;	zhead = matrix[8] = cos(beta) * cos(alpha);

	.globl	mkMatrix

	.extern	alpha	; from 3d.s
	.extern	beta		;
	.extern	gamma	;

	.phrase
;current trig vals

; uses:alpha, beta, gamma
; output: ds.w 9  pointed to by a1
;
; register usage:
; d3 = sin(alpha)
; d4 = sin(beta)
; d5 = sin(gamma)
; d6 = cos(alpha)
; d7 = cos(beta)
; a5 = cos(gamma)

mkMatrix:
	movem.l	d0-d7/a0-a6,-(sp)
	; fill current trig vals
	move.w	alpha, d0
	jsr		sin
	move.w	d0, d3

	move.w	beta, d0
	jsr		sin
	move.w	d0, d4

	move.w	gamma, d0
	jsr		sin
	move.w	d0, d5

	move.w	alpha, d0
	jsr		cos
	move.w	d0, d6

	move.w	beta, d0
	jsr		cos
	move.w	d0, d7

	move.w	gamma, d0
	jsr		cos
	move.w	d0, a5

	moveq	#14, d2
; fill the array
	;matrix[0] = cos(gamma) * cos(beta) + sin(gamma) * sin(beta) * sin(alpha);
	muls		d7, d0
	move.w	d5, d1
	muls		d4, d1
	moveq	#14, d2
	asr.l	d2, d1
	muls		d3, d1
	add.l    	d1, d0
	moveq	#14, d2
	asr.l	d2, d0
	move.w	d0, (a1)+
	;matrix[1] = sin(gamma) * cos(alpha);
	move.w	d5, d0
	muls		d6, d0
	moveq	#14, d2
	asr.l	d2, d0
	move.w	d0, (a1)+
	;matrix[2] = sin(gamma) * sin(alpha) * cos(beta) - cos(gamma) * sin(beta);
	move.w	d5, d0
	muls		d3, d0
	moveq	#14, d2
	asr.l	d2, d0
	muls		d7, d0
	move.w	a5, d1
	muls		d4, d1
	sub.l	d1, d0
	moveq	#14, d2
	asr.l	d2, d0
	move.w	d0, (a1)+
	;matrix[3] = cos(gamma) * sin(alpha) * sin(beta) - sin(gamma) * cos(beta);
	move.w	a5, d0
	muls		d3, d0
	moveq	#14, d2
	asr.l	d2, d0
	muls		d4, d0
	move.w	d5, d1
	muls		d7, d1
	sub.l	d1, d0
	moveq	#14, d2
	asr.l	d2, d0
	move.w	d0, (a1)+
	;matrix[4] = cos(gamma) * cos(alpha);
	move.w	a5, d0
	muls		d6, d0
	moveq	#14, d2
	asr.l	d2, d0
	move.w	d0, (a1)+
	;matrix[5] = cos(gamma) * sin(alpha) * cos(beta) + sin(gamma) * sin(beta);
	move.w	a5, d0
	muls		d3, d0
	moveq	#14, d2
	asr.l	d2, d0
	muls		d7, d0
	move.w	d5, d1
	muls		d4, d1
	add.l	d1, d0
	moveq	#14, d2
	asr.l	d2, d0
	move.w	d0, (a1)+
	;matrix[6] = sin(beta) * cos(alpha);
	move.w	d4, d0
	muls		d6, d0
	moveq	#14, d2
	asr.l	d2, d0
	move.w	d0, (a1)+
	;matrix[7] = -sin(alpha);
	move.w	d3, d0
	neg.w	d0
	move.w	d0, (a1)+
	;matrix[8] = cos(beta) * cos(alpha);
	move.w	d7, d0
	muls		d6, d0
	moveq	#14, d2
	asr.l	d2, d0
	move.w	d0, (a1)

	movem.l	(sp)+,d0-d7/a0-a6
	rts
